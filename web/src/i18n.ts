export function t(text: string, values?: Record<string, string | number>): string {
  const message = locale === 'en' ? messages[text] ?? text : text;
  return values ? message.replace(/\{(\w+)\}/g, (match, key: string) => values[key] == null ? match : String(values[key])) : message;
}
export function formatDate(ms?: number | null) {
  return ms ? new Date(ms).toLocaleString(locale === 'en' ? 'en-GB' : 'zh-CN', { hour12: false }) : '—';
}
