import { useSyncExternalStore } from 'react';

export type Locale = 'zh-CN' | 'en';
const languageKey = 'converyn.locale';
function savedLocale(): Locale {
  try { return localStorage.getItem(languageKey) === 'en' ? 'en' : 'zh-CN'; }
  catch { return 'zh-CN'; }
}
let locale = savedLocale();
const listeners = new Set<() => void>();
export const getLocale = () => locale;
export function setLocale(value: Locale) {
  locale = value;
  try { localStorage.setItem(languageKey, value); } catch { /* Language selection still works without storage. */ }
  document.documentElement.lang = value;
  document.title = value === 'en' ? 'Converyn Console' : 'Converyn 控制台';
  listeners.forEach(listener => listener());
}
export function useLocale() {
  return useSyncExternalStore(listener => { listeners.add(listener); return () => { listeners.delete(listener); }; }, getLocale);
}
